/**
 * Intelligent in-memory similarity & keyword search for RAG retrieval
 */
export function retrieveRelevantChunks(query: string, topK: number = 3): KnowledgeChunk[] {
  if (!query || query.trim() === "") {
    return KNOWLEDGE_BASE_CHUNKS.slice(0, topK);
  }

  const normalizedQuery = query.toLowerCase().replace(/[^\w\s]/g, " ");
  const queryTerms = normalizedQuery.split(/\s+/).filter((t) => t.length > 2);

  const scoredChunks = KNOWLEDGE_BASE_CHUNKS.map((chunk) => {
    let score = 0;
    const chunkTitle = chunk.title.toLowerCase();
    const chunkContent = chunk.content.toLowerCase();
    const chunkKeywords = chunk.keywords.map((k) => k.toLowerCase());

    queryTerms.forEach((term) => {
      // Direct keyword match in tags (highest weight)
      if (chunkKeywords.some((k) => k.includes(term) || term.includes(k))) {
        score += 8;
      }
      // Match in title (high weight)
      if (chunkTitle.includes(term)) {
        score += 5;
      }
      // Match in content
      const occurrences = (chunkContent.match(new RegExp(term, "g")) || []).length;
      score += Math.min(occurrences * 2, 10);
    });

    // Special intent boosts
    if (normalizedQuery.includes("fee") || normalizedQuery.includes("cost") || normalizedQuery.includes("price") || normalizedQuery.includes("pkr")) {
      if (chunk.category === "fees") score += 10;
    }
    if (normalizedQuery.includes("where") || normalizedQuery.includes("location") || normalizedQuery.includes("contact") || normalizedQuery.includes("address") || normalizedQuery.includes("number") || normalizedQuery.includes("whatsapp")) {
      if (chunk.category === "contact") score += 12;
    }
    if (normalizedQuery.includes("time") || normalizedQuery.includes("shift") || normalizedQuery.includes("hours") || normalizedQuery.includes("when")) {
      if (chunk.category === "timings") score += 12;
    }
    if (normalizedQuery.includes("apply") || normalizedQuery.includes("admission") || normalizedQuery.includes("document") || normalizedQuery.includes("join")) {
      if (chunk.category === "admissions") score += 10;
    }
    if (normalizedQuery.includes("course") || normalizedQuery.includes("python") || normalizedQuery.includes("web") || normalizedQuery.includes("graphic") || normalizedQuery.includes("ielts") || normalizedQuery.includes("css")) {
      if (chunk.category === "courses") score += 10;
    }

    return { chunk, score };
  });

  scoredChunks.sort((a, b) => b.score - a.score);

  return scoredChunks.slice(0, topK).map((item) => item.chunk);
}
